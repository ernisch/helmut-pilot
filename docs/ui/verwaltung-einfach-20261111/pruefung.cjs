// Lokale Abnahme des Entwurfs. Aufruf ausschließlich über scripts/lokal.js.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {createRequire}=require('node:module');
const requireProject=createRequire(path.resolve(__dirname,'../../../package.json'));
const {chromium}=requireProject('playwright');
const folder=__dirname;
let checks=0;
const check=(name,condition)=>{assert.ok(condition,name);checks++;console.log('PASS '+name);};
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-background-networking']});
 const errors=[],outbound=[];
 const context=await browser.newContext({viewport:{width:1440,height:1050},offline:true});
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',req=>{if(/^https?:/.test(req.url()))outbound.push(req.url());});
 try{
  await page.setContent(fs.readFileSync(path.join(folder,'vorschau.html'),'utf8'));
  await page.getByRole('heading',{name:'Was braucht dich heute?'}).waitFor();
  check('Drei Hauptbereiche',await page.locator('.nav button').count()===3);
  check('Entwurf und fiktive Daten sichtbar',await page.locator('.demo').isVisible());
  await page.screenshot({path:path.join(folder,'uebersicht-desktop.png'),fullPage:true});
  await page.locator('[data-customer="nord"]').first().click();
  check('Fehlendes Briefing und offene Ursache sichtbar',(await page.locator('main').innerText()).includes('Die Ursache ist noch nicht bestätigt.'));
  await page.getByRole('button',{name:'Versorgungsdetails ansehen'}).click();
  check('Details werden fokussiert',await page.locator('#supply').evaluate(el=>el===document.activeElement));
  await page.screenshot({path:path.join(folder,'kunde-desktop.png'),fullPage:true});
  await page.locator('[data-nav="customers"]').click();
  await page.locator('[data-customer="mitte"]').click();
  check('Technischer Erfolg und offenes Fachurteil getrennt',(await page.locator('main').innerText()).includes('inhaltliche Beurteilung ist offen'));
  check('Bereitstellung ist App-Quittung',await page.getByText('In App bereitgestellt',{exact:true}).isVisible());
  await page.locator('[data-nav="customers"]').click();
  await page.locator('[data-customer="west"]').click();
  check('Unbekannter Status ohne Erfolgsaussage',await page.getByText('Der aktuelle Zustand ist offen.',{exact:true}).isVisible());
  await page.locator('[data-nav="customers"]').click();
  await page.locator('#search').fill('gibt es nicht');
  check('Suche hat verständlichen Leerzustand',await page.getByText(/Keine Kunden gefunden/).isVisible());
  await page.locator('#search').fill('nord');
  check('Suche filtert Kunden',await page.locator('.customer').count()===1);
  await page.locator('[data-action="new"]').click();
  await page.getByRole('button',{name:'Weiter',exact:true}).click();
  check('Pflichtangaben verhindern Weiterschalten',await page.locator('#email').count()===1);
  await page.locator('#name').fill('   ');
  await page.locator('#person').fill('Synthetische Testperson');
  await page.locator('#email').fill('entwurf@example.invalid');
  await page.getByRole('button',{name:'Weiter',exact:true}).click();
  check('Leerzeichen ersetzen keinen Kundennamen',await page.locator('#name').isVisible());
  const unsafe='<img src=x onerror="window.__xss=true">';
  await page.locator('#name').fill(unsafe);
  await page.locator('#person').fill('Synthetische Testperson');
  await page.locator('#email').fill('entwurf@example.invalid');
  await page.getByRole('button',{name:'Weiter',exact:true}).click();
  await page.locator('#parliament').selectOption('Landtag');
  check('Landtag fordert Bundesland',await page.locator('#state').isVisible());
  await page.locator('#region').fill('Fiktive Region');
  await page.locator('#topic').fill('Fiktives Thema');
  await page.getByRole('button',{name:'Weiter',exact:true}).click();
  check('Fehlendes Bundesland sperrt nächsten Schritt',await page.locator('#state').isVisible());
  await page.locator('#state').selectOption('Berlin');
  await page.getByRole('button',{name:'Zurück',exact:true}).click();
  check('Rückweg erhält Kontakt',await page.locator('#name').inputValue()===unsafe);
  await page.getByRole('button',{name:'Weiter',exact:true}).click();
  check('Rückweg erhält Mandat',await page.locator('#region').inputValue()==='Fiktive Region');
  check('Rückweg erhält Bundesland',await page.locator('#state').inputValue()==='Berlin');
  await page.getByRole('button',{name:'Weiter',exact:true}).click();
  check('Review belässt Profilprüfung offen',await page.getByText('Prüfung offen',{exact:true}).isVisible());
  check('Review belässt Zugang gesperrt',await page.getByText('Gesperrt',{exact:true}).isVisible());
  check('Eingabe wird als Text ausgegeben',await page.locator('main img').count()===0&&await page.evaluate(()=>!window.__xss));
  await page.getByRole('button',{name:'Im Entwurf übernehmen',exact:true}).click();
  check('Neuer Kunde bleibt in Einrichtung',await page.getByText('Dieser Kunde ist noch in Einrichtung.',{exact:true}).isVisible());
  check('Keine vorgetäuschte Kontoanlage',await page.getByRole('status').innerText().then(t=>t.includes('Kein echtes Konto')));
  await page.locator('[data-nav="customers"]').click();
  await page.locator('#search').fill('entwurf@example.invalid');
  check('Übernommener Entwurf ist in Liste auffindbar',await page.locator('.customer').count()===1);
  await page.locator('.customer').click();
  check('XSS auch in Detailansicht ausgeschlossen',await page.locator('main img').count()===0&&await page.evaluate(()=>!window.__xss));
  await page.setViewportSize({width:320,height:900});
  check('Lange eingegebene Namen bleiben mobil lesbar',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.setViewportSize({width:1440,height:1050});
  await page.setContent('<!doctype html><title>Entwurf neu laden</title>');
  await page.goto('about:blank');
  await page.setContent(fs.readFileSync(path.join(folder,'vorschau.html'),'utf8'));
  check('Neu laden verwirft flüchtigen Entwurf',await page.locator('.customer').count()===4);
  for(const width of [1440,390,360,320]){
   await page.setViewportSize({width,height:900});
   for(const nav of ['overview','customers','settings']){
    await page.locator(`[data-nav="${nav}"]`).click();
    check(`Kein horizontaler Überlauf: ${nav} bei ${width}px`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   }
   await page.locator('[data-nav="customers"]').click();
   await page.locator('[data-customer="nord"]').click();
   check(`Kundenseite ohne Überlauf bei ${width}px`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   if(width===390)await page.screenshot({path:path.join(folder,'kunde-mobil.png'),fullPage:true});
   await page.locator('[data-nav="customers"]').click();
   await page.locator('[data-action="new"]').click();
   check(`Formular ohne Überlauf bei ${width}px`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   if(width===390)await page.screenshot({path:path.join(folder,'anlegen-mobil.png'),fullPage:true});
  }
  await page.setViewportSize({width:1440,height:1050});
  await page.locator('[data-nav="settings"]').click();
  await page.getByText('Erweiterte Werkzeuge',{exact:true}).click();
  check('Werkzeuge behalten Diagnose- und Recoveryzugang als Entwurf',(await page.locator('details').innerText()).includes('Recovery, Backfills und Testbriefing'));
  await page.locator('[data-nav="customers"]').click();
  await page.keyboard.press('Tab');
  check('Tastatur erreicht nächsten interaktiven Schritt',await page.evaluate(()=>document.activeElement.matches('button')));
  check('Keine JavaScriptfehler',errors.length===0);
  check('Keine externen Anfragen',outbound.length===0);
  const result={status:'PASS',date:new Date().toISOString(),scope:'Lokaler Offline-Entwurf mit fiktiven Daten; keine Productionpruefung',checks,browser:await browser.version(),widths:[1440,390,360,320],externalRequests:outbound.length,pageErrors:errors,screenshots:['uebersicht-desktop.png','kunde-desktop.png','kunde-mobil.png','anlegen-mobil.png']};
  fs.writeFileSync(path.join(folder,'pruefung.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result));
 }finally{await context.close();await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
